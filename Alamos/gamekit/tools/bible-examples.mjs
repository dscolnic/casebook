// bible-examples.mjs — the five worked examples, onto each mission.
//
//   node tools/bible-examples.mjs <theme> [--dry]
//   node tools/bible-examples.mjs --all [--dry]
//
// EVERY BIBLE NOW WRITES FIVE PER MISSION, under `### Worked examples - optional
// mission-card panel`: a problem, the rule it turns on, the steps worked out, the
// answer, and the mistake people make. 600 across the eight campaigns.
//
// They are reference the player chooses to open — the bible is explicit that this
// is "not an interaction to grade: no answer input, points, metric changes, or
// unlock requirement" — so nothing here goes near the question machinery. The job
// is to carry them whole and unedited onto the mission, beside the glossary and
// the equations that share their card.
//
// Written as one JSON flow value per example, the same way `bible-deeper` writes a
// review question: the block is the bible's own object and re-typing it key by key
// here would be a second description of what it already states exactly.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { readBible } from './bibleRead.mjs';

const gamekit = resolve(dirname(new URL(import.meta.url).pathname), '..');
const BIBLES = JSON.parse(readFileSync(resolve(gamekit, 'books/parts/bibles.json'), 'utf8'));

const args = process.argv.slice(2);
const dry = args.includes('--dry');
const themes = args.includes('--all')
  ? Object.keys(BIBLES).filter(k => !k.startsWith('_'))
  : args.filter(a => !a.startsWith('--'));
if(!themes.length){
  console.error('usage: node tools/bible-examples.mjs <theme>|--all [--dry]');
  process.exit(2);
}

let bad = 0;
for(const theme of themes){
  const path = BIBLES[theme];
  if(!path){ console.error(`${theme}: not in books/parts/bibles.json`); bad++; continue; }
  const bible = readBible(resolve(gamekit, path));
  const dir = resolve(gamekit, `books/parts/${theme}`);
  if(!existsSync(dir)){ console.error(`${theme}: no fragments`); bad++; continue; }

  let wrote = 0, examples = 0, none = 0;
  for(const part of readdirSync(dir).filter(f => /^m\d+\.ya?ml$/i.test(f))
    .sort((a, b) => (+a.match(/\d+/)[0]) - (+b.match(/\d+/)[0]))){
    const n = +part.match(/\d+/)[0];
    const bm = bible.missions.find(m => m.n === n);
    const w = bm?.worked;
    if(!w?.examples?.length){ none++; continue; }

    const file = resolve(dir, part);
    const lines = readFileSync(file, 'utf8').split('\n');
    const rows = ['  # The five worked examples the mission card offers behind a button.',
      '  # GENERATED by tools/bible-examples.mjs from the campaign bible. Reference,',
      '  # never graded — see the panel in engine/core/worked.js.',
      '  worked:',
      `    label: ${JSON.stringify(w.label)}`,
      `    title: ${JSON.stringify(w.title)}`,
      '    examples:'];
    for(const x of w.examples) rows.push(`    - ${JSON.stringify(x)}`);
    rows.push('');

    // Replaced where it is already there, otherwise before `stops:`, which every
    // fragment has and which follows the mission's own keys.
    const at = lines.findIndex(l => /^  worked:$/.test(l));
    if(at >= 0){
      let end = at + 1;
      while(end < lines.length && !/^  [a-z][A-Za-z]*:/.test(lines[end])) end++;
      while(end > at + 1 && /^\s*#/.test(lines[end - 1])) end--;
      let head = at;
      while(head > 0 && /^\s*#/.test(lines[head - 1])) head--;
      lines.splice(head, end - head, ...rows);
    } else {
      const where = lines.findIndex(l => /^  stops:$/.test(l));
      if(where < 0){ console.error(`${theme} m${n}: no \`stops:\` to place \`worked:\` before`); bad++; continue; }
      lines.splice(where, 0, ...rows);
    }
    if(!dry) writeFileSync(file, lines.join('\n'));
    wrote++; examples += w.examples.length;
  }
  console.log(`${theme.padEnd(22)} ${wrote} mission(s) · ${examples} worked example(s)`
    + (none ? ` · ${none} the bible writes none for` : '') + (dry ? '  — nothing written' : ''));
}
process.exit(bad ? 1 : 0);
