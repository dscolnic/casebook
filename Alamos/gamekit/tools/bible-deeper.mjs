// bible-deeper.mjs — the optional review, from the bible into each mission.
//
//   node tools/bible-deeper.mjs <theme> [--dry]
//   node tools/bible-deeper.mjs --all [--dry]
//
// Every bible writes one per mission under "Optional secondary brief and
// six-question review": a card of copy, some ideas kept off the required day
// card, and six multiple-choice questions with a hint and a line of feedback per
// option. Its own availability note is explicit — it changes no metric, no
// Recovery Point and no unlock — so what this carries is ungraded by
// construction and the game must keep it that way.
//
// Written in place beside `beats:` rather than by re-extracting, for the same
// reason every other tool here does: the fragments carry converted boards,
// syllabus numbers and resolved speakers that a re-extract would throw away.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { pathToFileURL } from 'node:url';
import { readBible } from './bibleRead.mjs';

const gamekit = resolve(dirname(new URL(import.meta.url).pathname), '..');
const BIBLES = JSON.parse(readFileSync(resolve(gamekit, 'books/parts/bibles.json'), 'utf8'));
const q = (s) => JSON.stringify(String(s ?? '').replace(/\s+/g, ' ').trim());

const args = process.argv.slice(2);
const RUN = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
const dry = args.includes('--dry');
const themes = args.includes('--all')
  ? Object.keys(BIBLES).filter(k => !k.startsWith('_'))
  : args.filter(a => !a.startsWith('--'));
if(RUN && !themes.length){
  console.error('usage: node tools/bible-deeper.mjs <theme>|--all [--dry]');
  process.exit(2);
}

let bad = 0;
for(const theme of (RUN ? themes : [])){
  const path = BIBLES[theme];
  if(!path){ console.error(`${theme}: not in books/parts/bibles.json`); bad++; continue; }
  const bible = readBible(resolve(gamekit, path));
  const dir = resolve(gamekit, `books/parts/${theme}`);
  if(!existsSync(dir)){ console.error(`${theme}: no fragments`); bad++; continue; }

  let wrote = 0, qs = 0, cs = 0, none = 0;
  for(const part of readdirSync(dir).filter(f => /^m\d+\.ya?ml$/i.test(f))
    .sort((a, b) => (+a.match(/\d+/)[0]) - (+b.match(/\d+/)[0]))){
    const n = +part.match(/\d+/)[0];
    const d = bible.missions.find(m => m.n === n)?.deeper;
    if(!d){ none++; continue; }
    const file = resolve(dir, part);
    const lines = readFileSync(file, 'utf8').split('\n');

    const rows = [
      '  # The optional review, offered when the mission is finished and graded',
      '  # nowhere. GENERATED by tools/bible-deeper.mjs from the campaign bible.',
      '  deeper:',
    ];
    if(d.intro) rows.push(`    intro: ${q(d.intro)}`);
    if(d.concepts.length){
      rows.push('    concepts:');
      for(const c of d.concepts){
        rows.push(c.name ? `    - {name: ${q(c.name)}, def: ${q(c.def)}}` : `    - {say: ${q(c.say)}}`);
      }
    }
    if(d.questions.length){
      rows.push('    questions:');
      for(const x of d.questions){
        rows.push(`    - prompt: ${q(x.prompt)}`);
        if(x.hint) rows.push(`      hint: ${q(x.hint)}`);
        rows.push(`      answer: ${q(x.answer)}`);
        // The chart, as one JSON flow value. It is the bible's own object and is
        // written straight back out rather than rebuilt key by key: a spec this
        // tool re-typed would be a second description of what figures.js takes.
        if(x.figure) rows.push(`      figure: ${JSON.stringify(x.figure)}`);
        rows.push('      options:');
        for(const o of x.options){
          rows.push(`      - {key: ${q(o.key)}, text: ${q(o.text)}`
            + (o.why ? `, why: ${q(o.why)}` : '') + '}');
        }
      }
    }
    rows.push('');

    // Replaced where it is already there, otherwise before `stops:`, which every
    // fragment has and which is what follows the mission's own keys.
    const at = lines.findIndex(l => /^  deeper:$/.test(l));
    if(at >= 0){
      let end = at + 1;
      while(end < lines.length && !/^  [a-z][A-Za-z]*:/.test(lines[end])) end++;
      while(end > at + 1 && /^\s*#/.test(lines[end - 1])) end--;
      let head = at;
      while(head > 0 && /^\s*#/.test(lines[head - 1])) head--;
      lines.splice(head, end - head, ...rows);
    } else {
      const where = lines.findIndex(l => /^  stops:$/.test(l));
      if(where < 0){ console.error(`${theme} m${n}: no \`stops:\` to place \`deeper:\` before`); bad++; continue; }
      lines.splice(where, 0, ...rows);
    }
    if(!dry) writeFileSync(file, lines.join('\n'));
    wrote++; qs += d.questions.length; cs += d.concepts.length;
  }
  console.log(`${theme.padEnd(22)} ${wrote} mission(s) · ${qs} question(s) · ${cs} extra concept(s)`
    + (none ? ` · ${none} the bible writes none for` : ''));
}
process.exitCode = bad ? 1 : 0;
