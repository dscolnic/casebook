// edition-addendum.mjs — the per-game page that goes with the grade-6 brief.
//
//   node tools/edition-addendum.mjs <theme>_ms            # to stdout
//   node tools/edition-addendum.mjs <theme>_ms --write    # books/convert/<theme>-addendum.md
//
// `books/GRADE6_BRIEF.md` is the same document for every game: what a stop is,
// the nineteen formats, the traps, the checklist. Everything that differs
// between games is here, and it is generated rather than written because all of
// it already exists somewhere in the repo — the syllabus in tools/syllabus.js,
// the cast in the theme's own content, the days in the book.
//
// The three things it exists to prevent, each of which has cost a round trip on
// the senior-high passes:
//
//   * a character arriving as a bare surname, because the writer had no cast list;
//   * an equation computed at a level the course does not reach, because nobody
//     said which ones were available;
//   * an area quietly dropped, because the day that taught it was hard to rewrite.
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import { writeFileSync, mkdirSync } from 'node:fs';
import { themeDir, editionBase } from '../engine/dev/registry.mjs';
import { SYLLABUS, EQUATIONS } from './syllabus.js';
import { fleschKincaid } from './readability.js';

const [name, ...flags] = process.argv.slice(2);
if(!name){
  console.error('usage: node tools/edition-addendum.mjs <theme>_ms [--write]');
  process.exit(2);
}
const base = editionBase(name);
if(!base){
  console.error(`${name} is not an edition of anything — there is no addendum to write`);
  process.exit(1);
}

const load = async (t) => (await import(pathToFileURL(resolve(themeDir(t), 'theme.js')).href)).default;
const mine = await load(name);
const theirs = await load(base);
const grade = Number(mine.audience?.grade ?? 6);

const MISSIONS = mine.content?.MISSIONS ?? [];
const GROUPS = mine.content?.GROUPS ?? [];
const ROSTER = mine.content?.ROSTER ?? [];
// A stop is a pointer — `{ group, lesson, task }` — and everything a player
// reads is in the lesson it points at. Reading the stop alone reports a
// campaign of empty scenes, which is what the first version of this page did.
const CURRICULUM = mine.content?.CURRICULUM ?? {};
const lessonOf = (stop) => (CURRICULUM[stop.group] ?? [])[stop.lesson] ?? null;
const groupName = Object.fromEntries(GROUPS.map(g => [g.id, g.name]));

const syl = SYLLABUS[name];
const eqs = EQUATIONS[name] ?? [];
const baseEqs = EQUATIONS[base] ?? [];
const out = [];
const w = (...l) => out.push(...l);

w(`# ${mine.title} — grade ${grade} edition: what is different about this game`,
  ``,
  `> Read this beside \`books/GRADE6_BRIEF.md\`. The brief is the same for every`,
  `> game; everything below is only true of this one. GENERATED by`,
  `> \`tools/edition-addendum.mjs\` — if something here is wrong, the syllabus or`,
  `> the book is wrong, not this page.`,
  ``,
  `The place, the cast and the story are **${theirs.title}**'s, unchanged. This`,
  `edition runs ${MISSIONS.length} ${(mine.dayNoun ?? 'day').toLowerCase()}s of the base game's`,
  `${(theirs.content?.MISSIONS ?? []).length}, and teaches a different course inside them.`,
  ``);

// ------------------------------------------------------------------ the cast
w(`## The cast — every name you may use, and nobody else`,
  ``,
  `At a person's **first mention in a rewritten passage, give the full name and`,
  `enough role that the sentence stands alone.** A bare surname arriving on day 6`,
  `has cost a round trip on every pass so far.`,
  ``,
  `| Person | Role | Area |`,
  `| --- | --- | --- |`);
for(const p of ROSTER){
  w(`| ${p.name} | ${p.role ?? ''} | ${groupName[p.division] ?? p.division ?? ''} |`);
}
w(``);

// ----------------------------------------------------------------- the areas
w(`## The areas — none of these may be dropped`,
  ``,
  `Each is a building in a world that is already built. If the grade-${grade} course`,
  `has no use for what one of them taught, **retarget it**: teach something a`,
  `sixth grader can learn standing in that room. A group with no stops is a room`,
  `the player walks into for nothing, and \`editionParity\` fails the game for it.`,
  ``,
  `| Area | What it taught at senior high | Stops here |`,
  `| --- | --- | --- |`);
const stopCount = {};
for(const m of MISSIONS) for(const s of m.stops ?? []) stopCount[s.group] = (stopCount[s.group] ?? 0) + 1;
const kindOf = (l) => String(l?.game?.type ?? l?.game?.format ?? '?').toUpperCase().replace(/[\s_-]+/g, '');
for(const g of GROUPS){
  w(`| ${g.name} | ${(g.desc ?? '').replace(/\|/g, '\\|')} | ${stopCount[g.id] ?? 0} |`);
}
w(``);

// ------------------------------------------------------------- the curriculum
w(`## The course at grade ${grade}`, ``);
if(!syl){
  w(`**No grade-${grade} syllabus is authored for this game yet.** Add one to`,
    `\`tools/syllabus.js\` under \`${name}\` before the writing pass — without it`,
    `nothing measures whether this edition teaches a course at all.`, ``);
} else {
  w(`${syl.course}`, ``,
    `Roughly follow it; the gaps are useful information. If something important is`,
    `taught nowhere, say so in your prose summary.`, ``);
  syl.concepts.forEach((c, i) => w(`${i + 1}. ${c.c}`));
  w(``);
}

// -------------------------------------------------------------- the equations
w(`## The equations this course may compute`, ``);
if(!eqs.length){
  w(`None are authored yet. Until they are, a question that computes anything is`,
    `computing something nobody has agreed this course teaches.`, ``);
} else {
  w(`Substitution into a one-line formula, with numbers chosen to stay manageable.`,
    `The formula is there to show where the answer comes from, not to be an`,
    `arithmetic obstacle.`, ``,
    `| Equation | What it is | Taught after |`,
    `| --- | --- | --- |`);
  for(const e of eqs) w(`| \`${e.e}\` | ${e.c} | ${(e.needs ?? []).map(n => '`' + n + '`').join(', ') || '—' } |`);
  w(``,
    `**Nothing is asked before the equation it is built out of** — \`equationOrder\``,
    `fails the game for it, and it counts a question that *computes* a number, not`,
    `one that mentions the relationship.`, ``);
}

const forbidden = baseEqs.filter(b => !eqs.some(e => e.e === b.e));
if(forbidden.length){
  w(`### What the senior-high course computes and this one does not`, ``,
    `These are in the base game. None of them may be computed here. Where a stop`,
    `leans on one, that stop is a redesign, not a rewrite.`, ``);
  for(const b of forbidden) w(`- \`${b.e}\` — ${b.c}`);
  w(``);
}

// -------------------------------------------------------------------- the days
w(`## The ten days as they stand`, ``,
  `Every one of these still carries the senior-high prose. The reading grade is`,
  `measured on the scene and the verdict together; the target is ${grade}, and`,
  `anything over ${grade + 2} fails the game outright.`, ``);

const DERIVE = [];
for(const [i, m] of MISSIONS.entries()){
  const stops = m.stops ?? [];
  const lessons = stops.map(lessonOf);
  const texts = lessons.flatMap(l => [l?.scene, l?.game?.why]
    .filter(t => typeof t === 'string' && t.split(/\s+/).length >= 12));
  const fk = texts.length ? texts.reduce((n, t) => n + fleschKincaid(t), 0) / texts.length : 0;
  w(`**${i + 1}. ${m.title}** — reads at grade ${fk.toFixed(1)}`);
  for(const [k, s] of stops.entries()){
    const l = lessons[k];
    const fmt = kindOf(l);
    if(fmt === 'DERIVE') DERIVE.push(`day ${i + 1}: ${l?.title ?? s.task}`);
    w(`  - \`${fmt}\` · ${groupName[s.group] ?? s.group} · ${l?.title ?? s.task ?? ''}`);
  }
  w(``);
}

if(DERIVE.length){
  w(`### ${DERIVE.length} stop(s) are \`DERIVE\`, which is not available at this level`, ``,
    `Its subject is algebraic manipulation and there is no grade-${grade} version of it.`,
    `Redesign each: a derivation that closes a ledger becomes \`BALANCE\`, one that`,
    `spends a finite quantity becomes \`ALLOCATE\`, one that pins a value between two`,
    `bounds becomes \`CLOUD\`.`, ``);
  DERIVE.forEach(d => w(`- ${d}`));
  w(``);
}

// ----------------------------------------------------------------- callbacks
const earlyAreas = [...new Set(MISSIONS.slice(0, 3).flatMap(m => (m.stops ?? []).map(s => groupName[s.group] ?? s.group)))];
w(`## The callbacks, which need review lessons`, ``,
  `From day 3 every day carries one extra stop revisiting an area taught earlier —`,
  `${Math.max(0, MISSIONS.length - 2)} of them across this campaign. The engine prefers a lesson titled`,
  `\`… — Review\` where one exists and re-asks the original question where it does`,
  `not, which is not spaced retrieval, it is repetition.`, ``,
  `Author review lessons on the areas taught earliest: ${earlyAreas.join(', ')}.`, ``);

// ------------------------------------------------------------- the argument
//
// Not derivable. The best this can do is say who the day cards actually talk
// about, and hand the judgement to a person — which is the honest shape for it.
const surname = (n) => String(n).split(/\s+/).pop();
const mentions = ROSTER.map(p => ({
  name: p.name,
  days: MISSIONS.map((m, i) => [i + 1, `${m.stake ?? ''} ${m.briefing ?? ''}`])
    .filter(([, t]) => t.includes(surname(p.name))).map(([d]) => d),
})).filter(p => p.days.length).sort((a, b) => b.days.length - a.days.length).slice(0, 4);

w(`## The argument`, ``,
  `A campaign has one argument between two named people, and **each of them is`,
  `right on some day** (\`STORY_SPEC.md\` §1). If one side is always right the`,
  `player learns a slogan. Nothing can check this automatically, so it is on you:`,
  `below is who the day cards actually name, and how often.`, ``);
for(const p of mentions) w(`- **${p.name}** — days ${p.days.join(', ')}`);
w(``,
  `Confirm against the base game that both sides still keep the day they win. If`,
  `the day one of them was right on was dropped, say so in your prose summary.`, ``);

const text = out.join('\n');
if(flags.includes('--write')){
  mkdirSync(resolve(themeDir(name), '..', '..', 'books', 'convert'), { recursive: true });
  const path = resolve(themeDir(name), '..', '..', 'books', 'convert', `${name}-addendum.md`);
  writeFileSync(path, text);
  console.log(`wrote books/convert/${name}-addendum.md — ${text.split('\n').length} lines`);
} else {
  console.log(text);
}
