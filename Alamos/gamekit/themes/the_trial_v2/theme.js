  // THE DAY MODEL IS OFF WHERE THE BARS ARE ON. The bible scores time and
  // correctness, so there are no funds, no day countdown and no priced ways out
  // of a wrong call — and two clocks on one screen is two clocks the player has
  // to choose between.
  economy: false,

  // ONE CALL AT A TIME.
  //
  // The day model opens every stop at once and lets the player plan the route.
  // The bible writes this campaign the other way — "Unlock Stop 2 at
  // `allocation-slate`", "unlock S3" — and its beat script is keyed to the stop
  // NUMBER that closed, not to how many have closed. Answer stop 4 second and
  // its beat is the one for stop 4, which does not exist; come back to stop 3
  // last and "Use the Stop 3 result to settle page one standard" arrives on the
