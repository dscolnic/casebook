import metrics from './metrics.js';
import { FIXTURES } from './fixtures.js';
import { decorate, fitOutRoom, fitOutSpine } from './props.js';
import { OPENING, ENDING } from './cards.js';

export default {
  // Who this edition is for. `engine/core/typography.js` reads it and scales the
  // root font size, so the same game can ship at several reading levels.
  // grade 4 scales 1.18x, 7 scales 1.10x, 13 and up not at all.
  audience: { grade: 12 },

  id: 'whiteout',
  title: 'Whiteout',
  subtitle: 'Software Lead · Aster Station',

  // Each mission is one day of the season before the aircraft comes in. The plan card prints this in front of the mission number.
  dayNoun: 'Day',

  // The morning card is a date stamp and two or three sentences: what happened,
  // and what you do about it. See gamekit/BRIEFING_PASS.md. The long form had to
  // carry a fortnight of context on a card read fifteen times, which is why the
  // stakes here ran to ninety words and grade 8 — and why nine of them were
  // failing the 90-word floor written for that form while also failing
  // plainCards. Opting in drops both floors, keeps the ceilings, and moves the
  // cast off the plan card onto the calls, where the player meets them anyway.
  // It also suppresses `deliveryPlanLine`; the Vestri Record is named on the
  // opening card and counted on the card that closes each day.
  stakeStyle: 'brief',

  // The place. `site.kind` picks the world module in vite.config.js:
  //   'outdoor'   engine/world/outdoorTown.js — buildings on terrain
  //   'interior'  engine/world/interiorSite.js — a spine with rooms off it
  // A theme whose place already exists may declare its own instead, with
  // `world: 'themes/<name>/world.js'` inside site.js. Deep Watch does.
  site,

  // Where the player starts the day, and which way they face. The day's budget
  // is measured from here, not from wherever the player is standing.
  start: site.spawn,

  // ------------------------------------------------- THE FOUR BARS
  //
  // Habitat Stability, Power Reserve, Control Reliability and Rescue Readiness,
  // with the recovery economy and the fifteen post-mission screens behind them.
  // The block is `metrics.js`, generated by tools/bible-metrics.mjs from §2 of
  // the campaign bible.
  //
  // WIRING IT IS WHAT TAKES THE DAY-1 RUN OUT. `warmupPlan` schedules an opener
  // only where `theme.metrics.bars` is empty, because a run in front of mission
  // 1 on a timed campaign is either time charged to a mission that has not
  // started or a tutorial wedged between the opening card and the first thing
  // the campaign says. The bible says so outright — "WHITEOUT authors no
  // pre-day sightseeing, greeting, or race warm-up; movement is learned inside
  // Mission 1" — and with the bars unwired the engine scheduled a greet run on
  // day 1 anyway, plus three more on days 4, 8 and 13.
  metrics,
  // NO WARM-UP RUNS AT ALL, which the bible states rather than implies: "WHITEOUT
  // authors no pre-day sightseeing, greeting, or race warm-up; movement is
  // learned inside Mission 1 while the player is already solving the heat
  // alarm." The bars clear day 1 on their own; this clears days 4, 8 and 13,
  // which were scheduling runs in the engine's own words because the book
  // authors no story for a run it never asked for.
  warmupRuns: false,
  // The bars are the score, so there is no funding round and no day countdown
  // beside them: two clocks on one screen is two clocks to choose between.
  economy: false,
  // The bible unlocks each stop from the one before ("Unlock: Stop 2"), and its
  // beat script is keyed to the stop number that closed. See STOPS_IN_ORDER.
  stopOrder: 'sequential',

  content: { GROUPS, MISSIONS, CURRICULUM, BALLPARK_CALCS, JARGON, ROSTER, LEADERS, AVATARS, COPY, WARMUPS },

  people: {
    OUTFITS,
    roleToOutfit,
    // spawn must be >= ROSTER.length, or characters past the limit never appear
    // and any mission stop naming them is unreachable. Validated.
    spawn: ROSTER.length,
    // Background people. A narrow place needs far fewer: on the submarine more
    // than eight and the player cannot get down the passage.
    extras: 18,
  },

  // What is inside each room the player walks into, from book.yml. Rooms are
  // built by engine/world/interiorBuilding.js on first entry, in a district
  // four kilometres from the town.
  interiors: INTERIORS,
  // The objects the questions are asked AT, one list per area — built on entry
  // by engine/world/interiorFixtures.js; catalogue in ./fixtures.js. The names
  // and the areas are the bible's §3; the wall each one stands against is ours.
  fixtures: FIXTURES,
  // How those rooms are built: 'lab' (vinyl, screens), 'timber' (board walls,
  // chalkboards, no screens anywhere) or 'steel' (painted plate, deck matting).
  interiorStyle: 'steel',

  // The title card: ONE paragraph. What the player is, where they are, and what
  // happens if the work is not done — the situation, and nothing else. The
  // rules of a day (order, clock, the price of a wrong call) used to be a
  // second paragraph here and in every game, and it was the part nobody read:
  // four sentences of mechanics standing between the player and the game, all
  // of it discoverable in the first minute of play or from the plan card.
  // ---------------------------------------------------------- the delivery
  //
  // What the fifteen-day season produces, and the one room the parts of it are kept in.
  // The opening card names it, the plan card says which piece today is, the card
  // that closes a day hands that piece over, and the board in the room named by
  // `where` is where all of them can be seen at once — engine/core/delivery.js.
  //
  // One finding a day, in the order the evidence changes the case: surface clock,
  // common measurement scale, separate ice and gas clocks, then the signed limits.
  delivery: {
    name: 'The Recovery Record',
    what:
      'Fifteen tested findings tell the next crew which faults were code, what '
      + 'proves it, and which repairs passed new inputs.',
    where: 'OPS',
    pieces: [
      'The integer arithmetic alarm',
      'The two branches that fired',
      'The loop that never advanced',
      'The shared utility fault',
      'The live object reference',
      'The missing minute digit',
      'The room sensor index',
      'The skipped recovery records',
      'The swapped map coordinates',
      'The bounded frequency search',
      'The separate warning fields',
      'The private rescue queue',
      'The terminating relay route',
      'The failed rollback test',
      'The staged station release',
    ],
  },
  // The bible's own opening sequence, verbatim — see themes/whiteout/cards.js.
  opening: OPENING,

  // The last thing anybody reads. Says what happened, what it cost and what is
  // unfinished, and takes all three from the fifteen days the player worked.
  // The bible's own ending card, verbatim — see cards.js.
  ending: ENDING,

  look: {
    fov: 66,            // a 72° field distorts badly down a straight street
    near: 0.1,
    // Outdoors this has to reach past the horizon ranks and the sky dome. At an
    // interior's 160 the dome is clipped away entirely and the sky renders
    // black, in broad daylight, with no error anywhere.
    far: 900,
    // Ice fog and blowing snow: a pale, close horizon with nothing behind it.
    fog: { colour: 0xd6dee6, near: 190, far: 620 },
    // Below 1.0 outdoors, or a mid albedo under a bright sky IBL blows out.
    // Snow is the brightest ground in the set and blows out first.
    exposure: 0.80,
    // How wide the player is, for collision. 0.45 suits a street; a place with
    // metre-wide doorways needs 0.3 or the player gets stuck in them.
    playerRadius: 0.45,
    // Six real lights is the ceiling. buildSunRig makes three of them.
    // A low sun and a bright surface: more bounce than anywhere else here.
    lighting: { ambient: 0.10, sun: 2.6, hemi: 0.42, shadowExtent: 140 },
  },

  // Theme hooks. `decorate` is called by the outdoor world, the two fit-out
  // hooks by the interior one; the unused ones are ignored.
  decorate,
  fitOutRoom,
  fitOutSpine,
};
